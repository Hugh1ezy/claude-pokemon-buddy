// Generates the firmware-embedded CJK glyph bitmaps for the local-clock
// screen's ganzhi (stem-branch) date row. Renders each glyph with the same
// Zpix pixel font already used everywhere else in this project's CJK
// rendering (host/src/render/layout.js), at 24px (a clean multiple of
// Zpix's 12px grid -- matches the size already used for weather text).
// Regenerate: cd host && node scripts/gen-ganzhi-font.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createCanvas, GlobalFonts } from "@napi-rs/canvas";

import { thresholdTo1bpp } from "../src/render/dither.js";

const ZPIX_FONT_PATH = fileURLToPath(new URL("../seed/fonts/zpix.ttf", import.meta.url));
GlobalFonts.registerFromPath(ZPIX_FONT_PATH, "Zpix");

const SIZE = 24; // px, square glyph cell -- clean Zpix multiple (12px grid x2)

// Order matters: index must match firmware's stem/branch numbering (0=jia..9=gui,
// 0=zi..11=hai), plus 4 label glyphs and 1 separator appended after.
const STEMS = ["甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸"];
const BRANCHES = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"];
const LABELS = ["年", "月", "日", "时"]; // index 22-25
const SEPARATOR = ["·"]; // index 26

const GLYPHS = [...STEMS, ...BRANCHES, ...LABELS, ...SEPARATOR];

function renderGlyph(ch) {
  const canvas = createCanvas(SIZE, SIZE);
  const g = canvas.getContext("2d");
  g.imageSmoothingEnabled = false;
  g.fillStyle = "#ffffff";
  g.fillRect(0, 0, SIZE, SIZE);
  g.fillStyle = "#000000";
  g.textBaseline = "alphabetic";
  g.font = `800 ${SIZE}px "Zpix"`;
  // Center on the glyph's ACTUAL ink bounding box, not nominal font metrics --
  // a fixed baseline offset (the previous approach) silently clipped every
  // glyph's bottom row against the canvas edge (confirmed via
  // scripts/check-ganzhi-clip.mjs: 100% of glyphs had ink on the last pixel
  // row). actualBoundingBox* reports the real drawn extent, so this
  // guarantees centered placement regardless of the font's internal
  // baseline/descent quirks.
  const m = g.measureText(ch);
  const inkW = m.actualBoundingBoxLeft + m.actualBoundingBoxRight;
  const inkH = m.actualBoundingBoxAscent + m.actualBoundingBoxDescent;
  const originX = Math.round((SIZE - inkW) / 2 + m.actualBoundingBoxLeft);
  const originY = Math.round((SIZE - inkH) / 2 + m.actualBoundingBoxAscent);
  g.fillText(ch, originX, originY);
  const { data } = g.getImageData(0, 0, SIZE, SIZE);
  const gray = new Uint8Array(SIZE * SIZE);
  for (let i = 0; i < SIZE * SIZE; i += 1) gray[i] = data[i * 4]; // R channel (grayscale render)
  return thresholdTo1bpp(gray, SIZE, SIZE);
}

function toCRows(bitmap) {
  const rowBytes = Math.ceil(SIZE / 8); // 3 bytes/row at 24px
  const rows = [];
  for (let y = 0; y < SIZE; y += 1) {
    const bytes = [];
    for (let b = 0; b < rowBytes; b += 1) bytes.push(bitmap.bytes[y * rowBytes + b]);
    rows.push(`{${bytes.map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(",")}}`);
  }
  return rows;
}

function generateInc() {
  const lines = [
    "// AUTO-GENERATED by host/scripts/gen-ganzhi-font.mjs. Do not edit by hand.",
    "// Regenerate: cd host && node scripts/gen-ganzhi-font.mjs",
    "// 27 glyphs: 10 heavenly stems, 12 earthly branches, 4 labels (年月日时),",
    "// 1 separator (·). Each glyph is 24x24 1-bit, 3 bytes/row, MSB = leftmost pixel.",
    `#define GANZHI_GLYPH_SIZE ${SIZE}`,
    `#define GANZHI_GLYPH_ROW_BYTES ${Math.ceil(SIZE / 8)}`,
    `#define GANZHI_GLYPH_COUNT ${GLYPHS.length}`,
    "// index layout: [0-9]=stem, [10-21]=branch, [22]=nian(年) [23]=yue(月) [24]=ri(日) [25]=shi(时), [26]=separator(·)",
    `static const uint8_t GANZHI_FONT[GANZHI_GLYPH_COUNT][${SIZE}][${Math.ceil(SIZE / 8)}] = {`,
  ];
  GLYPHS.forEach((ch, i) => {
    const bitmap = renderGlyph(ch);
    lines.push(`  { // ${i}: ${ch}`);
    lines.push(`    ${toCRows(bitmap).join(",\n    ")}`);
    lines.push("  },");
  });
  lines.push("};");
  return lines.join("\n") + "\n";
}

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isCli) {
  const out = fileURLToPath(new URL("../../firmware/main/ganzhi_font.inc", import.meta.url));
  writeFileSync(out, generateInc());
  console.log(`wrote ${out} (${GLYPHS.length} glyphs, ${SIZE}x${SIZE})`);
}

export { GLYPHS, renderGlyph, SIZE };
